#!/bin/sh
# Regenerates native/core/src/session/vendored from herdr-mobile's herdr-tui, `acp` and keeper, or checks it
# is current.
#
#   scripts/sync-vendored.sh              copy the modules from the sibling checkout, apply the patch
#   scripts/sync-vendored.sh --check      generate into a temp folder and fail if the tree differs
#   scripts/sync-vendored.sh --make-patch rewrite vendored.patch from what the vendored tree holds now
#                                         (edit the vendored files, then run this)
#   HERDR_MOBILE=/path scripts/sync-vendored.sh   another checkout (default: ../herdr-mobile)
#   HERDR_CORE=/path/to/core ...                   another herdr-core folder (default: native/core)
#
# Why vendored (docs/ARCHITECTURE.md): depending on the `herdr-tui` crate turns on syntect's `regex-onig`
# for the whole build, which makes nsh-base's own syntect types non-Send and breaks nsh-base. The
# reducer (`session`, `transcript`, `queue`, `risk`, `attach`, `question`) is pure, so those modules are
# copied: `crate::` becomes `crate::session::vendored::`, `question.rs` loses its ratatui panel, and `session.rs`
# asks this crate for its client name. The `acp` crate (JSON-RPC and ACP message parsing, pure serde) is
# copied too, as `vendored/acp`, because a desktop chat needs what upstream's parser drops (terminal output,
# tool locations, boolean options, usage). Those changes, and the ones to `keeper.py` (what the keeper tells
# an agent it can do), are `native/core/src/session/vendored.patch`; nothing else is edited by hand.
# docs/ACP.md lists every change and why; the patch is the candidate for upstreaming to herdr-mobile.
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
up=${HERDR_MOBILE:-$root/../herdr-mobile}
src=$up/rust/crates/viewer/src
acp_src=$up/rust/crates/acp/src
core=${HERDR_CORE:-$root/native/core}
dest=$core/src/session/vendored
patch_file=$core/src/session/vendored.patch
mods="attach diff elapsed question queue risk session transcript width"
acp_mods="config permission rpc update"

[ -d "$src" ] || { echo "sync-vendored: no herdr-mobile checkout at $up" >&2; exit 66; }
rev=$(git -C "$up" rev-parse --short HEAD)
dirty=$(git -C "$up" status --porcelain -- rust/crates/viewer rust/crates/acp rust/crates/keeper app/lib/data/services/keeper_script.dart | wc -l)

mode=${1:-write}
mkdir -p "$root/.scratch"
stage=$(mktemp -d "$root/.scratch/sync-stage.XXXXXX")
trap 'rm -rf "$stage"' EXIT
mkdir -p "$stage/acp"

# Upstream, rewritten, before our patch.
for m in $mods; do
  {
    echo "// Vendored from herdr-mobile rust/crates/viewer/src/$m.rs (see UPSTREAM). Regenerated by scripts/sync-vendored.sh; do not edit."
    sed -e 's/crate::/crate::session::vendored::/g' -e 's/\bacp::/crate::session::vendored::acp::/g' "$src/$m.rs"
  } > "$stage/$m.rs"
done
for m in $acp_mods; do
  {
    echo "// Vendored from herdr-mobile rust/crates/acp/src/$m.rs (see UPSTREAM). Regenerated by scripts/sync-vendored.sh; do not edit."
    sed 's/crate::/crate::session::vendored::acp::/g' "$acp_src/$m.rs"
  } > "$stage/acp/$m.rs"
done
{
  echo "// Vendored from herdr-mobile rust/crates/acp/src/lib.rs (see UPSTREAM). Regenerated by scripts/sync-vendored.sh; do not edit."
  sed 's/crate::/crate::session::vendored::acp::/g' "$acp_src/lib.rs"
} > "$stage/acp/mod.rs"

# The keeper (python, one file shared with the phone app) with the agent table filled in, as herdr-tui's
# build.rs bakes it, and the table itself (the start form lists agents from it).
python3 - "$up" "$stage" <<'PY'
import json, sys
up, out = sys.argv[1], sys.argv[2]
dart = open(up + "/app/lib/data/services/keeper_script.dart").read()
start = "const keeperPython = r'''\n"
body = dart.split(start, 1)[1].rsplit("\n''';", 1)[0]
assert "@@ROUTES@@" in body
routes = json.loads(open(up + "/rust/crates/keeper/routes.json").read())
open(out + "/keeper.py", "w").write(body.replace("@@ROUTES@@", json.dumps(routes, separators=(", ", ": "))) + "\n")
open(out + "/routes.json", "w").write(json.dumps(routes, indent=2) + "\n")
PY

files="$(for m in $mods; do echo $m.rs; done) $(for m in $acp_mods mod; do echo acp/$m.rs; done) keeper.py routes.json"

if [ "$mode" = "--make-patch" ]; then
  : > "$patch_file"
  for f in $files; do
    # `diff` exits 1 when the files differ, which is the point.
    diff -u --label "a/$f" --label "a/$f" "$stage/$f" "$dest/$f" >> "$patch_file" || true
  done
  echo "sync-vendored: wrote $patch_file ($(wc -l < "$patch_file") lines) against herdr-mobile $rev"
  exit 0
fi

(cd "$stage" && patch -s -p1 < "$patch_file")

out=$dest
if [ "$mode" = "--check" ]; then
  out=$(mktemp -d "$root/.scratch/sync-out.XXXXXX")
  trap 'rm -rf "$stage" "$out"' EXIT
fi
mkdir -p "$out/acp"
for f in $files; do cp "$stage/$f" "$out/$f"; done
cat > "$out/UPSTREAM" <<EOT
herdr-mobile $rev
modules: $mods, acp ($acp_mods), keeper.py, routes.json
EOT

if [ "$mode" = "--check" ]; then
  # Only the generated files: `vendored/mod.rs`, `text.rs` and UPSTREAM are ours.
  bad=""
  for f in $files; do
    cmp -s "$out/$f" "$dest/$f" || bad="$bad $f"
  done
  if [ -z "$bad" ]; then
    echo "sync-vendored: up to date with herdr-mobile $rev"
  else
    for f in $bad; do diff -u "$out/$f" "$dest/$f" | head -40 >&2 || true; done
    echo "sync-vendored: differs from herdr-mobile $rev:$bad (run scripts/sync-vendored.sh)" >&2
    exit 1
  fi
else
  echo "sync-vendored: copied from herdr-mobile $rev"
fi
if [ "$dirty" != "0" ]; then
  echo "sync-vendored: warning: herdr-mobile has uncommitted changes in what was copied" >&2
fi
